import '../models/vpn_models.dart';

class OvpnParser {
  static OvpnProfileModel parse({
    required String raw,
    required String name,
    String fileName = 'imported.ovpn',
    String source = 'ovpn',
    String? overrideSubtitle,
  }) {
    final lines = raw.split(RegExp(r'\r?\n'));
    String host = '';
    int port = 1194;
    String proto = 'udp';
    String cipher = 'AES-256-GCM';
    bool auth = false;
    String sni = '';

    for (final rawLine in lines) {
      final line = rawLine.trim();
      if (line.isEmpty || line.startsWith('#') || line.startsWith(';') || line.startsWith('<')) {
        continue;
      }
      final parts = line.split(RegExp(r'\s+'));
      final key = parts.first.toLowerCase();

      switch (key) {
        case 'remote':
          if (parts.length > 1) host = parts[1];
          if (parts.length > 2) port = int.tryParse(parts[2]) ?? port;
          if (parts.length > 3) {
            proto = parts[3].toLowerCase().contains('tcp') ? 'tcp' : 'udp';
          }
          break;
        case 'port':
          if (parts.length > 1) port = int.tryParse(parts[1]) ?? port;
          break;
        case 'proto':
          if (parts.length > 1) proto = parts[1].toLowerCase();
          break;
        case 'cipher':
        case 'data-ciphers':
          if (parts.length > 1) cipher = parts[1].split(':').first;
          break;
        case 'auth-user-pass':
          auth = true;
          break;
        case 'sni':
        case 'tls-sni':
          if (parts.length > 1) sni = parts[1];
          break;
      }
    }

    if (host.isEmpty) {
      final match = RegExp(r'(?:Host:|SNI:|@)([a-zA-Z0-9.-]+\.[a-zA-Z]{2,})(?::(\d+))?')
          .firstMatch(raw);
      if (match != null) {
        host = match.group(1) ?? '127.0.0.1';
        port = int.tryParse(match.group(2) ?? '') ?? port;
      } else {
        host = '127.0.0.1';
      }
    }

    final hasCa = RegExp(r'<ca>[\s\S]*?</ca>', caseSensitive: false).hasMatch(raw);
    final isTg = source == 'telegram' ||
        raw.toLowerCase().contains('telegram') ||
        raw.contains('t.me/');

    return OvpnProfileModel(
      id: 'cfg_${DateTime.now().millisecondsSinceEpoch}',
      name: name,
      subtitle: overrideSubtitle ?? '$host:$port · ${proto.toUpperCase()}',
      fileName: fileName,
      source: isTg ? 'telegram' : source,
      rawContent: raw,
      remoteHost: host,
      remotePort: port,
      protocol: proto,
      cipher: cipher,
      sniHost: sni,
      hasCaCert: hasCa,
      requiresAuth: auth,
    );
  }

  static String buildFromVps(VpsServerModel vps) {
    final protoDirective = vps.protocol.toUpperCase() == 'UDP' ? 'udp' : 'tcp-client';
    final buffer = StringBuffer()
      ..writeln('# Generated by Hamo Tunnel Plus')
      ..writeln('client')
      ..writeln('dev tun')
      ..writeln('proto $protoDirective')
      ..writeln('remote ${vps.host} ${vps.port}')
      ..writeln('resolv-retry infinite')
      ..writeln('nobind')
      ..writeln('persist-key')
      ..writeln('persist-tun')
      ..writeln('remote-cert-tls server')
      ..writeln('cipher AES-256-GCM')
      ..writeln('auth SHA256')
      ..writeln('keepalive ${vps.keepAliveSec} 60')
      ..writeln('tun-mtu ${vps.mtu}')
      ..writeln('dhcp-option DNS ${vps.dnsPrimary}')
      ..writeln('auth-user-pass')
      ..writeln('verb 3');

    if (vps.sniHost.trim().isNotEmpty) {
      buffer.writeln('http-proxy-option CUSTOM-HEADER Host ${vps.sniHost.trim()}');
    }

    return buffer.toString();
  }

